// PxgArticulationCoreDesc layout fixture: the address map every articulation
// shader reads the core descriptor through (pxgSlangArticulationDesc.slang's
// PXG_ARTI_CORE_* constants), pinned two ways.
//
//   * static_asserts against the REAL engine header -- the constant matches the
//     C++ offset;
//   * artiCoreDescProbe (artiCoreDescProbe.slang) reads every mapped field back
//     through its named constant -- the SHADER reads at the offset it names.  A
//     static_assert alone cannot see a constant used at the wrong call site.
//
// Until PhysX 5.6.1 both lived in testDmaArtiResidual.cpp, beside
// dmaArticulationResidual -- the kernel that first forced this map (P8.66) and
// whose fixture P8.82 extended with the probe.  5.12 removed the kernel with the
// solver residual reporting; the map and its pins are what every other
// articulation fixture still relies on, so they moved here.  (The residual-only
// pins -- PxgArticulation::{internal,contact}ResidualAccumulator and
// sizeof(Dy::ErrorAccumulator) -- went with the kernel.)
//
// The values below are the PhysX 5.12 ones, re-derived from the 5.12 header with
// offsetof when the articulation area was ported.

