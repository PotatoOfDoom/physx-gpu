# gen_kernel_manifest.py — RUNTIME_PLAN.md P3/P4: generate the Slang kernel
# manifest that maps each of the 501 CUDA registry kernel IDs
# (PxgKernelNames.h, enum order) to the compiled Slang SPIR-V module + entry
# point that replaces it.  The mapping is by exact CUDA-function-name equality:
# the Phase-1 launch-kernel ports keep the CUDA __global__ name as the Slang
# entry name, so a name match is an exact functional correspondence.  Registry
# kernels with no matching entry (not yet ported, or ported under an
# abbreviated helper name that P4 will map by hand) get a null row.
#
# The emitted header is the index table the Vulkan kernel-wrangler / shim use
# to turn a PxgKernelIds::X into (spirvFile, entry); it also carries the exact
# CUDA name per row so the port coverage can be audited and drift from the
# registry is caught by the manifest test.
#
#   python3 gen_kernel_manifest.py <PxgKernelNames.h> <tests/CMakeLists.txt> <out.h>

import re
import sys


def parse_registry(path):
    text = open(path).read()
    return re.findall(r'KERNEL_DEF\(\s*(\w+)\s*,\s*"([^"]+)"\s*\)', text)


def parse_entries(cmake_path):
    text = open(cmake_path).read()
    entry2spirv = {}
    for m in re.finditer(r'pxg_compile_shader\(([^\)]*)\)', text, re.S):
        toks = m.group(1).split()
        if not toks:
            continue
        stem, entries = toks[0], toks[1:]
        for e in entries:
            # First definition wins; entries are unique across the suite.
            entry2spirv.setdefault(e, stem + '.spv')
    return entry2spirv


def main():
    names_h, cmake, out = sys.argv[1], sys.argv[2], sys.argv[3]
    kernels = parse_registry(names_h)
    entry2spirv = parse_entries(cmake)

    rows = []
    mapped = 0
    for enum, cuda in kernels:
        spirv = entry2spirv.get(cuda)
        if spirv:
            mapped += 1
        rows.append((enum, cuda, spirv))

    lines = []
    lines.append('// GENERATED by tools/gen_kernel_manifest.py — DO NOT EDIT.')
    lines.append('// Maps the CUDA registry kernel IDs (PxgKernelNames.h, enum order) to the')
    lines.append('// Slang SPIR-V module + entry that replaces each.  Regenerate after adding')
    lines.append('// kernels; the p4Manifest test fails if this drifts from the registry.')
    lines.append('#ifndef PXG_SLANG_KERNEL_MANIFEST_H')
    lines.append('#define PXG_SLANG_KERNEL_MANIFEST_H')
    lines.append('')
    lines.append('namespace physx { namespace gpuslang {')
    lines.append('')
    lines.append('struct PxgSlangKernelRow')
    lines.append('{')
    lines.append('    const char* cudaName;   // CUDA __global__ name (registry key)')
    lines.append('    const char* spirvFile;  // Slang SPIR-V module, or nullptr if unmapped')
    lines.append('    const char* entry;      // Slang entry point, or nullptr if unmapped')
    lines.append('};')
    lines.append('')
    lines.append(f'static const unsigned PXG_SLANG_KERNEL_COUNT = {len(rows)};')
    lines.append(f'static const unsigned PXG_SLANG_KERNEL_MAPPED = {mapped};')
    lines.append('')
    lines.append('// Indexed by PxgKernelIds::<ENUM> (enum order matches this array order).')
    lines.append('static const PxgSlangKernelRow gPxgSlangKernelManifest[] = {')
    for enum, cuda, spirv in rows:
        if spirv:
            entry = cuda
            lines.append(f'    {{ "{cuda}", "{spirv}", "{entry}" }},  // {enum}')
        else:
            lines.append(f'    {{ "{cuda}", nullptr, nullptr }},  // {enum} (unmapped)')
    lines.append('};')
    lines.append('')
    lines.append('} } // namespace physx::gpuslang')
    lines.append('')
    lines.append('#endif // PXG_SLANG_KERNEL_MANIFEST_H')
    open(out, 'w').write('\n'.join(lines) + '\n')

    print(f'wrote {out}: {len(rows)} rows, {mapped} mapped '
          f'({100.0 * mapped / len(rows):.1f}% of the registry)')


if __name__ == '__main__':
    main()
